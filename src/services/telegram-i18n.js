const CATALOGS = Object.freeze({ en: EN, pt: PT });

function interpolate(template, values) {
  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (_match, key) => {
    if (!Object.hasOwn(values, key)) {
      throw new TypeError(`Missing Telegram translation value: ${key}`);
    }
    return String(values[key]);
  });
}

function createTelegramTranslator(languageCode) {
  const locale = resolveTelegramLocale(languageCode);
  const catalog = CATALOGS[locale] || EN;
  function t(key, values = {}) {
    const template = catalog[key] ?? EN[key];
    if (typeof template !== 'string') {
      throw new TypeError(`Missing Telegram translation: ${key}`);
    }
    return interpolate(template, values);
  }
  return Object.freeze({ locale, t });
}

